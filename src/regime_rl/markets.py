"""Static market definitions: benchmark and macro ETFs, sector maps and curated universes.

The US universe is fetched live (see :mod:`regime_rl.data.universe`); EU and CN use
the curated lists below because no free, reliable constituent feed exists for them.
"""

from __future__ import annotations

from dataclasses import dataclass, field


@dataclass(frozen=True)
class Market:
    code: str
    name: str
    benchmark: str
    bond_etf: str
    credit_etf: str
    growth_etf: str
    smallcap: str
    sector_map: dict[str, tuple[str, ...]]
    tickers: tuple[str, ...] | None = None  # None -> fetch live constituents
    extra: dict = field(default_factory=dict)

    @property
    def sector_etfs(self) -> tuple[str, ...]:
        return tuple(self.sector_map)

    @property
    def macro_etfs(self) -> tuple[str, ...]:
        """Benchmark + macro ETFs, deduplicated, order preserved."""
        seen: dict[str, None] = {}
        for t in (self.benchmark, self.growth_etf, self.smallcap, self.bond_etf, self.credit_etf):
            seen.setdefault(t, None)
        return tuple(seen)

    @property
    def all_etfs(self) -> tuple[str, ...]:
        seen = dict.fromkeys(self.macro_etfs)
        for t in self.sector_etfs:
            seen.setdefault(t, None)
        return tuple(seen)


