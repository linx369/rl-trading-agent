MARKETS: dict[str, Market] = {m.code: m for m in (US, EU, CN)}


def get_market(code: str) -> Market:
    try:
        return MARKETS[code.upper()]
    except KeyError as exc:
        raise ValueError(f"Unknown market {code!r}; choose from {sorted(MARKETS)}") from exc
